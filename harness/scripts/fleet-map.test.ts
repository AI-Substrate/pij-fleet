describe("project defaults, through the pij shim", () => {
	function shim(args: readonly string[], cwd: string): Run {
		const r = spawnSync(process.execPath, [SHIM, "fleet-map", ...args], { cwd, encoding: "utf8" });
		return { status: r.status, stdout: r.stdout, stderr: r.stderr };
	}

	it("init writes into governance once; generate writes the main checkout's scratch/fleet-map/", () => {
		const { repo, gov } = project(true);
		const structure = join(gov, ".harness", "government", "fleet-map", "fleet-map.structure.json");
		const init = shim(["init"], repo);
		expect(init.status).toBe(0);
		// the printed next step is a command that works as printed
		const folder = join(realpathSync(gov), ".harness", "government", "fleet-map");
		const add = `git -C ${folder} add fleet-map.structure.json`;
		expect(init.stdout).toContain(`new file: run \`${add}\` before committing`);
		expect(spawnSync("sh", ["-c", add]).status).toBe(0);
		const staged = spawnSync("git", ["-C", gov, "diff", "--cached", "--name-only"], {
			encoding: "utf8",
		});
		expect(staged.stdout.trim()).toBe(".harness/government/fleet-map/fleet-map.structure.json");
		expect(existsSync(structure)).toBe(true);
		const again = shim(["init"], repo);
		expect(again.status).toBe(2);
		expect(again.stderr).toContain("never overwrites");

		const gen = shim(["generate", "--offline", "--at", AT], gov);
		expect(gen.status, gen.stderr).toBe(0);
		const out = join(repo, "scratch", "fleet-map");
		expect(listing(out)).toEqual(["fleet-map.data.js", "fleet-map.standalone.html", "index.html"]);
		expect(gen.stderr).toContain("is not git-ignored");

		writeFileSync(join(repo, ".gitignore"), "scratch/\n");
		expect(shim(["generate", "--offline", "--at", AT], repo).stderr).not.toContain("git-ignored");
		const open = shim(["open"], repo);
		expect(open.stdout.trim()).toMatch(/^file:\/\/.*\/scratch\/fleet-map\/index\.html$/);
	});

	it("with no governance worktree it refuses and prints the --structure form", () => {
		const { repo } = project(false);
		const r = shim(["generate", "--offline"], repo);
		expect(r.status).toBe(2);
		expect(r.stderr).toContain("0 worktrees on branch prime-governance");
		expect(r.stderr).toContain(
			"pij fleet-map generate --structure <path to fleet-map.structure.json>",
		);
		expect(existsSync(join(repo, "scratch"))).toBe(false);
	});

	it("outside a repository it names the flag to pass", () => {
		const r = shim(["generate", "--offline"], scratch());
		expect(r.status).toBe(2);
		expect(r.stderr).toContain("pass --structure <path>");
	});
});
