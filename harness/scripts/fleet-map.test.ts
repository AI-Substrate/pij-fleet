function scratch(): string {
	return mkdtempSync(join(tmpdir(), "pij-fleet-map-"));
}

/** The data object a generated fleet-map.data.js carries. */
function dataOf(dir: string): Record<string, unknown> {
	const text = readFileSync(join(dir, "fleet-map.data.js"), "utf8");
	return JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));
}

function listing(dir: string): string[] {
	return readdirSync(dir, { recursive: true }).map(String).sort();
}

function git(cwd: string, ...args: string[]): void {
	const r = spawnSync("git", ["-C", cwd, ...args], { encoding: "utf8" });
	if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`);
}

/** A repo with one commit, and optionally a prime-governance worktree beside it. */
function project(withGovernance: boolean): { repo: string; gov: string } {
	const base = scratch();
	const repo = join(base, "repo");
	const gov = join(base, "repo-governance");
	mkdirSync(repo);
	git(repo, "init", "-q", "-b", "main");
	git(
		repo,
		"-c",
		"user.name=t",
		"-c",
		"user.email=t@t",
		"commit",
		"-q",
		"--allow-empty",
		"-m",
		"c",
	);
	if (withGovernance) {
		git(repo, "worktree", "add", "-q", "-b", "prime-governance", gov);
		mkdirSync(join(gov, ".harness", "government"), { recursive: true });
	}
	return { repo, gov };
}

