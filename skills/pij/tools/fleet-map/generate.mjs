#!/usr/bin/env node
// pij fleet-map: a project's workstreams drawn as a metro map. Node, no dependencies.
//
//   pij fleet-map init [--dir <d>]
//   pij fleet-map generate [--structure <p>] [--out <d>] [--at <iso>] [--offline] [--project <slug>]
//   pij fleet-map open [--out <d>] [--launch]
//
// Run in a project's repo with no flags: the hand-kept structure is
// <government-root>/fleet-map/fleet-map.structure.json (the repo's one prime-governance
// worktree), and the page and data go to <main checkout>/scratch/fleet-map/.
// Same world in, same bytes out: keys are sorted, arrays keep the structure's order, and
// `generatedAt` is the only field that moves (pin it with --at).

