export function fnv1a(s) {
	let h = 0x811c9dc5;
	for (const ch of s) {
		h ^= ch.codePointAt(0);
		h = Math.imul(h, 0x01000193) >>> 0;
	}
	return h;
}

const STOP_STATES = [
	"merged",
	"review",
	"building",
	"blocked",
	"held",
	"waiting",
	"next",
	"later",
	"closed",
];
const PHASES = ["done", "now", "next", "later"];
const RESULT_WORD = { pass: "PASS", "pass-with-notes": "PASS WITH NOTES", block: "BLOCK" };

const USAGE = `pij fleet-map: a project's workstreams drawn as a metro map (static page + data).

Usage:
  pij fleet-map init [--dir <d>]                write the starter structure (refuses to overwrite)
  pij fleet-map generate [--structure <p>] [--out <d>] [--at <iso>] [--offline] [--project <slug>]
                                                write ${DATA_FILE} and copy the page next to it
  pij fleet-map open [--out <d>] [--launch]     print the page's file:// URL; --launch opens it

Run in a project's repo, the structure is <government-root>/fleet-map/${STRUCTURE_FILE}
(the repo's one prime-governance worktree) and the output is <main checkout>/scratch/fleet-map/.
Paths inside the skill's own folder are refused. Generated files say: ${HEADER}.`;

const VERBS = {
	init: { values: ["--dir"], switches: [] },
	generate: { values: ["--structure", "--out", "--at", "--project"], switches: ["--offline"] },
	open: { values: ["--out"], switches: ["--launch"] },
};

export class Refusal extends Error {}

export function parseArgs(argv) {
	const [verb, ...rest] = argv;
	if (verb === undefined || verb === "--help" || verb === "-h" || verb === "help")
		return { help: true };
	const spec = VERBS[verb];
	if (spec === undefined) throw new Refusal(`unknown verb ${verb}\n\n${USAGE}`);
	const flags = {};
	for (let i = 0; i < rest.length; i++) {
		const token = rest[i];
		if (token === "--help" || token === "-h") return { help: true };
		const eq = token.indexOf("=");
		const name = eq === -1 ? token : token.slice(0, eq);
		if (spec.switches.includes(name) && eq === -1) flags[name] = true;
		else if (spec.values.includes(name)) {
			const value = eq === -1 ? rest[++i] : token.slice(eq + 1);
			if (value === undefined || value === "") throw new Refusal(`${name} needs a value`);
			flags[name] = value;
		} else throw new Refusal(`${verb} does not take ${token}\n\n${USAGE}`);
	}
	return { verb, flags };
}

// ---------- the skill copy is never written through ----------

/** The realpath of `p`, or of its nearest existing ancestor joined with the rest. */
function realOrAncestor(p) {
	const missing = [];
	let at = resolve(p);
	for (;;) {
		try {
			return join(realpathSync(at), ...missing.reverse());
		} catch {
			const parent = dirname(at);
			if (parent === at) return resolve(p);
			missing.push(basename(at));
			at = parent;
		}
	}
}

export function insideSkill(p, toolDir = TOOL_DIR) {
	const tool = realpathSync(toolDir);
	const rel = relative(tool, realOrAncestor(p));
	return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
}

function guard(flag, p) {
	if (insideSkill(p))
		throw new Refusal(
			`${flag} ${p} is inside the skill's own folder (${realpathSync(TOOL_DIR)}); the skill copy is never written. Use a project path.`,
		);
	return resolve(p);
}

/** Writes a fresh regular file: a link at the target is removed, never written through. */
function writeFresh(path, text) {
	rmSync(path, { force: true });
	writeFileSync(path, text, { flag: "wx" });
}

// ---------- where the project keeps things ----------

function git(cwd, args) {
	try {
		return execFileSync("git", ["-C", cwd, ...args], {
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
			env: { ...process.env, GIT_OPTIONAL_LOCKS: "0" },
		});
	} catch {
		return null;
	}
}

/** The main checkout and the one prime-governance worktree, by government-root.sh's rules. */
export function projectLayout(cwd) {
	const top = git(cwd, ["rev-parse", "--show-toplevel"]);
	if (top === null) return { repo: null };
	const listed = git(cwd, ["worktree", "list", "--porcelain", "-z"]) ?? "";
	const trees = [];
	for (const field of listed.split("\0")) {
		if (field.startsWith("worktree ")) trees.push({ path: field.slice(9) });
		else if (field.startsWith("branch ") && trees.length)
			trees[trees.length - 1].branch = field.slice(7);
	}
	const gov = trees.filter((t) => t.branch === "refs/heads/prime-governance");
	const root = gov.length === 1 ? join(gov[0].path, ".harness", "government") : null;
	return {
		repo: top.trim(),
		main: trees[0]?.path ?? top.trim(),
		governance: root !== null && existsSync(root) && statSync(root).isDirectory() ? root : null,
		governanceWhy:
			gov.length !== 1
				? `${top.trim()} has ${gov.length} worktrees on branch prime-governance (expected one, holding .harness/government)`
				: `${root} is not available`,
	};
}

function needRepo(layout, flag) {
	if (layout.repo === null)
		throw new Refusal(`not inside a git repository, so there is no default; pass ${flag} <path>`);
}

function structurePath(flags, layout) {
	if (flags["--structure"]) return guard("--structure", flags["--structure"]);
	needRepo(layout, "--structure");
	if (layout.governance === null)
		throw new Refusal(
			`no governance worktree: ${layout.governanceWhy}.\nPass the structure instead: pij fleet-map generate --structure <path to ${STRUCTURE_FILE}>`,
		);
	return guard("--structure", join(layout.governance, "fleet-map", STRUCTURE_FILE));
}

function outDir(flags, layout) {
	if (flags["--out"]) return guard("--out", flags["--out"]);
	needRepo(layout, "--out");
	return guard("--out", join(layout.main, "scratch", "fleet-map"));
}

// ---------- live sources (read only) ----------

function exec(cmd, argv, cwd) {
	try {
		const out = execFileSync(cmd, argv, {
			cwd,
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
			maxBuffer: 64 << 20,
		});
		return { ok: true, out };
	} catch (error) {
		return { ok: false, missing: error.code === "ENOENT" };
	}
}

/** A pij v2 envelope's data, or a warning naming why there is none. */
function pijData(argv, cwd, warnings) {
	const label = `pij ${argv.filter((a) => a !== "--json").join(" ")}`;
	const r = exec("pij", argv, cwd);
	if (!r.ok) {
		warnings.push(`${label} failed${r.missing ? ": pij is not on PATH" : ""}`);
		return null;
	}
	try {
		const env = JSON.parse(r.out);
		if (env.ok === false) {
			warnings.push(`${label} refused: ${env.details?.code ?? env.error ?? "unknown"}`);
			return null;
		}
		return env.data ?? null;
	} catch {
		warnings.push(`${label} was not parseable`);
		return null;
	}
}

export function allStops(stops, out = []) {
	for (const s of stops || []) {
		out.push(s);
		allStops(s.stops, out);
	}
	return out;
}

function prNumbers(structure) {
	const lines = [...(structure.lines || []), ...(structure.sidings || [])];
	const prs = lines.flatMap((l) => allStops(l.stops)).map((s) => s.pr);
	return [...new Set(prs.filter(Boolean))].sort((a, b) => a - b);
}

/** One `pij list`, one `pij directory`, and per PR one `gh pr view` and one `pij outputs`. */
export function collect(structure, { cwd, project }) {
	const warnings = [];
	const proj = project ? ["--project", project] : [];
	const sources = { prs: {}, outputs: {}, warnings, gh: true };
	sources.seats = pijData(["list", "--json"], cwd, warnings)?.seats ?? null;
	sources.roles = pijData(["directory", "--json", ...proj], cwd, warnings)?.roles ?? null;
	for (const n of prNumbers(structure)) {
		if (sources.gh) {
			const fields = "number,state,headRefOid,baseRefName,title,url,comments";
			const r = exec("gh", ["pr", "view", String(n), "--json", fields], cwd);
			if (r.ok) {
				try {
					sources.prs[n] = JSON.parse(r.out);
				} catch {
					warnings.push(`gh pr view ${n} was not parseable`);
				}
			} else if (r.missing) {
				sources.gh = false;
				warnings.push("gh is not on PATH: PR state, head and title are not shown");
			} else warnings.push(`gh pr view ${n} failed`);
		}
		const subject = ["outputs", "--subject", `pr:${n}`, "--json", ...proj];
		sources.outputs[n] = pijData(subject, cwd, warnings)?.outputs ?? null;
	}
	return sources;
}

// ---------- verdicts: pij's outputs first, PR comments for the roles pij lacks ----------

const VERDICT_RE =
	/\b(PASS WITH NOTES|PASS|FAIL|BLOCKED|AGREED|MECHANICAL|CHANGES REQUESTED|REQUEST CHANGES)\b/;
export function parseVerdict(body) {
	// The verdict sits on the first line, or just under a "MERGE BLOCKED UNTIL" header.
	const lines = body
		.split("\n")
		.filter((l) => l.trim())
		.slice(0, 4);
	const isHead = (l) => /verdict/i.test(l) || /^\**\s*role:[a-z-]+/i.test(l.replace(/^#+\s*/, ""));
	const first = lines.find((l) => isHead(l) && VERDICT_RE.test(l));
	if (!first) return null;
	const v = first.match(VERDICT_RE);
	const roleTag = first.match(/role:([a-z][a-z-]*)/i);
	const roleWord = first.match(/([A-Za-z][A-Za-z-]*)\s+verdict/i);
	const role = (roleTag ? roleTag[1] : roleWord ? roleWord[1] : "review").toLowerCase();
	const sha = first.match(/(?:\bat\s+|@)([0-9a-f]{7,40})\b/);
	return { role, verdict: v[1], at: sha ? sha[1].slice(0, 9) : null };
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const day = (ms) => new Date(ms).toISOString().slice(0, 10);

/** Per role, the newest pij verdict (one at `head` first); a comment only where pij has none. */
export function verdictsFor(outputs, comments, head) {
	const best = new Map();
	const rank = (o) => [head && o.head === head ? 1 : 0, o.at ?? 0, o.path ?? ""];
	for (const o of outputs || []) {
		if (o.kind !== "verdict" || !o.role) continue;
		const cur = best.get(o.role);
		if (!cur || rank(o).reduce((c, x, i) => c || cmp(x, rank(cur)[i]), 0) > 0) best.set(o.role, o);
	}
	const out = [...best.values()].map((o) => ({
		role: o.role,
		verdict: RESULT_WORD[o.result] ?? String(o.result).toUpperCase(),
		at: o.head ? o.head.slice(0, 9) : null,
		atHead: head && o.head ? o.head === head : null,
		on: typeof o.at === "number" ? day(o.at) : null,
		source: "pij",
	}));
	const byRole = new Map();
	const sorted = [...(comments || [])].sort((a, b) => cmp(a.createdAt, b.createdAt));
	for (const c of sorted) {
		const v = parseVerdict(c.body || "");
		if (v && !best.has(v.role)) byRole.set(v.role, { ...v, on: c.createdAt.slice(0, 10) });
	}
	for (const v of byRole.values()) {
		const atHead = v.at && head ? head.startsWith(v.at.slice(0, 7)) : null;
		out.push({ role: v.role, verdict: v.verdict, at: v.at, atHead, on: v.on, source: "comment" });
	}
	return out.sort((a, b) => cmp(a.role, b.role));
}

// ---------- assemble (pure: structure + sources in, data out) ----------

export function assignColours(structure) {
	const assigned = [];
	for (const line of [...(structure.lines || []), ...(structure.sidings || [])]) {
		if (!line.colour) {
			line.colour = PALETTE[fnv1a(String(line.id)) % PALETTE.length];
			assigned.push(`${line.id} ${line.colour}`);
		}
	}
	return assigned;
}

export function buildData(structure, sources, { offline, generatedAt }) {
	const warnings = [...(sources?.warnings ?? [])];
	const seats = {};
	const seatContext = {};
	for (const s of sources?.seats ?? []) {
		seats[s.id] = s.state || s.badge || "unknown";
		const ctx = s.sessionStatus?.status?.contextUsedTokens?.value ?? s.contextUsed;
		// rounded to the nearest 1k so a seat ticking over by a few tokens doesn't churn the file
		if (typeof ctx === "number") seatContext[s.id] = Math.round(ctx / 1000);
	}
	const roleDir = {};
	for (const r of sources?.roles ?? []) roleDir[r.id] = r;
	const prs = {};
	for (const [n, p] of Object.entries(sources?.prs ?? {})) {
		prs[n] = {
			state: p.state,
			head: p.headRefOid.slice(0, 9),
			base: p.baseRefName,
			title: p.title,
			url: p.url,
			verdicts: verdictsFor(sources.outputs?.[n], p.comments, p.headRefOid),
		};
	}
	for (const [n, outputs] of Object.entries(sources?.outputs ?? {})) {
		if (!prs[n] && outputs?.length) prs[n] = { verdicts: verdictsFor(outputs, [], null) };
	}

	// One entry per (role, seat). A seat the structure names but the directory doesn't list live
	// for that role is "released"; a role with no seat named takes the directory's live holders.
	function communityOut(roles) {
		const out = [];
		for (const r of roles || []) {
			const dir = roleDir[r.role];
			const live = new Set((dir?.live || []).map((h) => h.seat));
			const named = r.seats || (r.seat ? [r.seat] : null);
			const list = named || (live.size ? [...live] : [null]);
			for (const seat of list) {
				const e = { role: r.role, title: dir?.title || r.role, seat: seat || null };
				if (offline) e.state = "unknown";
				else if (!seat || !live.has(seat)) e.state = "released";
				else e.state = seats[seat] || "absent";
				if (seat && seatContext[seat] !== undefined && e.state !== "released")
					e.contextK = seatContext[seat];
				const lo = dir?.latest_output;
				// a role's latest output belongs to the seat that wrote it, not to every holder
				if (lo && seat && (lo.writer === seat || (!lo.writer && list.length === 1)))
					e.lastOutput = {
						at: new Date(lo.at).toISOString().replace(/\.\d{3}Z$/, "Z"),
						kind: lo.kind || null,
						subject: lo.subject || null,
						result: lo.result || null,
					};
				out.push(e);
			}
		}
		return out.sort((a, b) => cmp(a.role, b.role) || cmp(a.seat || "", b.seat || ""));
	}

	function stopOut(s, lineState) {
		const live = s.pr && prs[s.pr];
		let state = s.state || (s.pr ? "review" : lineState === "later" ? "later" : "next");
		if (live?.state) {
			if (live.state === "MERGED") state = "merged";
			else if (live.state === "CLOSED") state = "closed";
			else if (state === "merged") state = "review";
		} else if (s.pr && !offline) state = s.state || "review";
		if (!STOP_STATES.includes(state)) warnings.push(`stop ${s.id}: unknown state ${state}`);
		const o = { id: s.id, name: s.name, state };
		if (s.pr) o.pr = s.pr;
		if (live) {
			o.title = live.title;
			o.url = live.url;
			o.head = live.head;
			o.base = live.base;
			o.verdicts = live.verdicts;
		}
		if (s.owner) {
			o.owner = s.owner;
			if (s.owner.startsWith("pij-") && !offline) o.ownerState = seats[s.owner] || "absent";
		}
		if (s.waitingOn && state !== "merged") o.waitingOn = s.waitingOn;
		if (s.note) o.note = s.note;
		if (s.stops?.length) o.stops = s.stops.map((c) => stopOut(c, lineState));
		return o;
	}

	function lineOut(l) {
		if (!PHASES.includes(l.state)) warnings.push(`line ${l.id}: unknown state ${l.state}`);
		const stops = (l.stops || []).map((s) => stopOut(s, l.state));
		const o = { id: l.id, name: l.name, colour: l.colour, state: l.state, stops };
		if (l.joins) o.joins = l.joins;
		if (l.joinsLine) {
			o.joinsLine = l.joinsLine;
			o.at = l.at;
		}
		if (l.roadmap) o.roadmap = l.roadmap;
		if (l.roles) o.community = communityOut(l.roles);
		return o;
	}

	const spine = structure.spine || [];
	const spineIds = new Set(spine.map((s) => s.id));
	if (structure.focus && !spineIds.has(structure.focus))
		warnings.push(`focus ${structure.focus} is not a spine station`);
	for (const l of [...(structure.lines || []), ...(structure.sidings || [])]) {
		if (l.joins && !spineIds.has(l.joins))
			warnings.push(`line ${l.id} joins unknown station ${l.joins}`);
	}
	const focus =
		spine.find((x) => x.id === structure.focus) || spine.find((x) => x.state === "now") || spine[0];
	const used = ["pij list", "pij directory", "pij outputs", ...(sources?.gh ? ["gh pr view"] : [])];
	return {
		title: structure.title || "Fleet",
		generatedAt,
		// the station the page opens on: the structure's "focus", else the first "now", else the first
		focus: focus?.id ?? null,
		source: offline ? "structure only (--offline)" : used.join(", "),
		spine: spine.map((s) => ({
			id: s.id,
			name: s.name,
			state: s.state,
			...(s.note ? { note: s.note } : {}),
		})),
		lines: (structure.lines || []).map(lineOut),
		sidings: (structure.sidings || []).map(lineOut),
		depot: structure.depot
			? { name: structure.depot.name || "Depot", community: communityOut(structure.depot.roles) }
			: null,
		warnings: [...warnings].sort(),
	};
}

/** Stable stringify: object keys sorted, arrays in order. */
export function stable(v, ind = "") {
	if (Array.isArray(v)) {
		if (!v.length) return "[]";
		const i2 = `${ind}  `;
		return `[\n${v.map((x) => i2 + stable(x, i2)).join(",\n")}\n${ind}]`;
	}
	if (v && typeof v === "object") {
		const keys = Object.keys(v)
			.filter((k) => v[k] !== undefined)
			.sort();
		if (!keys.length) return "{}";
		const i2 = `${ind}  `;
		return `{\n${keys.map((k) => `${i2 + JSON.stringify(k)}: ${stable(v[k], i2)}`).join(",\n")}\n${ind}}`;
	}
	return JSON.stringify(v);
}

export function dataText(data) {
	return `// ${HEADER}\nwindow.FLEET_MAP = ${stable(data)};\n`;
}

export function pageText(template) {
	const end = template.indexOf("\n") + 1;
	return `${template.slice(0, end)}<!-- ${HEADER} -->\n${template.slice(end)}`;
}

// ---------- verbs ----------

function init(flags, layout, log) {
	let dir;
	if (flags["--dir"]) dir = guard("--dir", flags["--dir"]);
	else {
		needRepo(layout, "--dir");
		if (layout.governance === null)
			throw new Refusal(
				`no governance worktree: ${layout.governanceWhy}.\nPass a folder instead: pij fleet-map init --dir <folder for ${STRUCTURE_FILE}>`,
			);
		dir = guard("--dir", join(layout.governance, "fleet-map"));
	}
	const target = join(dir, STRUCTURE_FILE);
	if (existsSync(target) || lstatSync(target, { throwIfNoEntry: false }))
		throw new Refusal(`${target} already exists; init never overwrites a structure`);
	mkdirSync(dir, { recursive: true });
	writeFresh(target, readFileSync(join(TEMPLATES, "structure.example.json"), "utf8"));
	log(`wrote ${target}\nedit it (spine, lines, stops), then run: pij fleet-map generate`);
}

function generate(flags, layout, log, warn) {
	const sPath = structurePath(flags, layout);
	const out = outDir(flags, layout);
	const offline = flags["--offline"] === true;
	const generatedAt = flags["--at"] ?? new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
	if (!existsSync(sPath))
		throw new Refusal(`no structure at ${sPath}; create one with: pij fleet-map init`);
	const structure = JSON.parse(readFileSync(sPath, "utf8"));
	const assigned = assignColours(structure);
	if (assigned.length) {
		// written back so a line's colour never changes; guard() keeps this the project's own file
		writeFileSync(sPath, `${JSON.stringify(structure, null, 2)}\n`);
		warn(`colour written back to ${sPath}: ${assigned.join(", ")}`);
	}
	const cwd = layout.repo === null ? process.cwd() : layout.main;
	const sources = offline ? null : collect(structure, { cwd, project: flags["--project"] });
	const data = buildData(structure, sources, { offline, generatedAt });
	mkdirSync(out, { recursive: true });
	writeFresh(join(out, DATA_FILE), dataText(data));
	writeFresh(join(out, PAGE_FILE), pageText(readFileSync(join(TEMPLATES, PAGE_FILE), "utf8")));
	ignoredCheck(out, warn);
	const prs = Object.keys(sources?.prs ?? {}).length;
	log(`wrote ${join(out, PAGE_FILE)} (${prs} PRs, ${data.warnings.length} warnings)`);
}

/** A warning, never a refusal, when the output sits in a repo that would track it. */
function ignoredCheck(out, warn) {
	if (git(out, ["rev-parse", "--show-toplevel"]) === null) return;
	if (git(out, ["check-ignore", "-q", PAGE_FILE]) === null)
		warn(
			`${out} is not git-ignored: add it (or scratch/) to .gitignore. pij fleet-map never commits.`,
		);
}

function open(flags, layout, log, warn) {
	const page = join(outDir(flags, layout), PAGE_FILE);
	const url = pathToFileURL(page).href;
	if (!existsSync(page)) warn(`${page} is not generated yet: run pij fleet-map generate`);
	log(url);
	if (flags["--launch"]) {
		const opener = process.platform === "darwin" ? "/usr/bin/open" : "xdg-open";
		if (!exec(opener, [url], process.cwd()).ok) warn(`could not launch ${opener}; open ${url}`);
	}
}

export function main(argv, { cwd = process.cwd(), log = console.log, warn = console.error } = {}) {
	try {
		const parsed = parseArgs(argv);
		if (parsed.help) {
			log(USAGE);
			return 0;
		}
		const layout = projectLayout(cwd);
		const verbs = { init, generate, open };
		verbs[parsed.verb](parsed.flags, layout, log, (m) => warn(`pij fleet-map: ${m}`));
		return 0;
	} catch (error) {
		if (!(error instanceof Refusal)) throw error;
		warn(`pij fleet-map: ${error.message}`);
		return 2;
	}
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url))
	process.exitCode = main(process.argv.slice(2));
